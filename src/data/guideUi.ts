const map: Record<Locale, GuideUi> = { en, pl, zh, ru, de };
const supported: Locale[] = ['pl', 'en', 'zh', 'ru', 'de'];

export type UiParams = Record<string, string | number>;

export function uiT(locale: string) {
  const ui = map[(supported as string[]).includes(locale) ? (locale as Locale) : 'en'] || en;
  return (key: string, params?: UiParams): string => {
    let s = ui[key] ?? en[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      }
    }
    return s;
  };
}

export function getGuideUi(locale: string): GuideUi {
  return map[(supported as string[]).includes(locale) ? (locale as Locale) : 'en'] || en;
}
